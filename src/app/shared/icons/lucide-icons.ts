const WRAP_OPEN = (size: number) =>
  `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">`;

export function lucideSvg(name: string, size = 16): string {
  let inner = LUCIDE_INNERS[name];
  if (!inner) return "";
  if (inner.startsWith("__ALIAS__")) {
    const target = inner.slice("__ALIAS__".length);
    inner = LUCIDE_INNERS[target] ?? "";
  }
  if (!inner) return "";
  return `${WRAP_OPEN(size)}${inner}</svg>`;
}

export function withIconSize(svg: string, size?: number): string {
  if (!svg || size == null) return svg;
  return svg
    .replace(/width="\d+"/, `width="${size}"`)
    .replace(/height="\d+"/, `height="${size}"`);
}
